#!/usr/bin/env bash
# Run the benchmark queries with EXPLAIN (ANALYZE, BUFFERS) and write RESULTS.md.
#
# Measurement, not estimation: every plan and timing in RESULTS.md comes from
# this script running against the live database. Nothing is transcribed by hand,
# because a benchmark number typed into prose is a benchmark nobody can re-run.
#
#   ./warehouse/benchmarks/run.sh
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DB="${ATLAS_DATABASE_URL:-${DATABASE_URL:-postgresql:///atlas_data}}"
OUT="$DIR/RESULTS.md"

command -v psql >/dev/null || { echo "psql not found" >&2; exit 1; }
psql "$DB" -Atc 'SELECT 1' >/dev/null || { echo "cannot reach $DB" >&2; exit 1; }

{
  echo "<!-- Generated by warehouse/benchmarks/run.sh. Do not edit by hand. -->"
  echo
  echo "# Benchmark results"
  echo
  echo "Generated $(date -u '+%Y-%m-%d %H:%M UTC') against PostgreSQL"
  echo "$(psql "$DB" -Atc 'SHOW server_version')."
  echo
  echo "Every plan below is \`EXPLAIN (ANALYZE, BUFFERS, WAL, SETTINGS)\` on the"
  echo "populated database after \`ANALYZE\`. WAL is reported because a plan that"
  echo "writes when it should only read is a defect the timing alone hides;"
  echo "SETTINGS names every non-default planner GUC, so a plan that only"
  echo "reproduces on one machine says so. Row counts at measurement time:"
  echo
  psql "$DB" -Atc "
    SELECT '- ' || t || ': ' || to_char(n, 'FM999,999,999')
      FROM (VALUES
        ('obs.observation',        (SELECT count(*) FROM obs.observation)),
        ('obs.composition_member', (SELECT count(*) FROM obs.composition_member)),
        ('source.field_value',     (SELECT count(*) FROM source.field_value)),
        ('mart.fact_observation',  (SELECT count(*) FROM mart.fact_observation))
      ) AS v(t, n);"
  echo
} > "$OUT"

# Split queries.sql on "-- name:" markers.
python3 - "$DIR/queries.sql" "$OUT" "$DB" <<'PY'
import subprocess, sys, re
src, out, db = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(src).read()
blocks = re.split(r"^-- name: (.+)$", text, flags=re.M)[1:]
with open(out, "a") as fh:
    for i in range(0, len(blocks), 2):
        name, sql = blocks[i].strip(), blocks[i + 1].strip()
        sql = "\n".join(l for l in sql.splitlines()
                        if not l.strip().startswith("--")).strip()
        if not sql:
            continue
        fh.write(f"## {name}\n\n```sql\n{sql}\n```\n\n```\n")
        fh.flush()
        r = subprocess.run(
            ["psql", db, "-X", "-q", "-A", "-t",
             "-c", f"EXPLAIN (ANALYZE, BUFFERS, WAL, SETTINGS) {sql}"],
            capture_output=True, text=True)
        fh.write((r.stdout or r.stderr).strip() + "\n```\n\n")
PY

echo "wrote $OUT"
